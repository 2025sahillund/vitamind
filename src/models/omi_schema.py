from typing import List, Optional, Dict, Any, Union
from pydantic import BaseModel, Field


class OmiTranscriptSegment(BaseModel):
    """Segment representing an utterance captured by Omi."""
    text: str = Field(description="Spoken text in this segment")
    speaker: Optional[str] = Field(default=None, description="Speaker identifier, e.g., SPEAKER_00")
    speaker_id: Optional[int] = Field(default=None, alias="speakerId")
    speaker_name: Optional[str] = Field(default=None)
    is_user: Optional[bool] = Field(default=None)
    start: Optional[float] = Field(default=None, description="Start offset in seconds")
    end: Optional[float] = Field(default=None, description="End offset in seconds")

    model_config = {"extra": "ignore", "populate_by_name": True}


class OmiStructuredData(BaseModel):
    """Pre-processed structured summary generated by Omi cloud."""
    title: Optional[str] = Field(default=None)
    summary: Optional[str] = Field(default=None)
    overview: Optional[str] = Field(default=None)
    action_items: Optional[List[Any]] = Field(default_factory=list)
    category: Optional[str] = Field(default=None)
    emoji: Optional[str] = Field(default=None)

    model_config = {"extra": "ignore"}


class OmiMemoryPayload(BaseModel):
    """
    Standard memory trigger webhook payload sent by Omi.
    Documented at https://docs.omi.me/
    """
    id: str = Field(description="Unique Omi memory ID")
    created_at: Optional[str] = Field(default=None, description="ISO timestamp of memory creation")
    started_at: Optional[str] = Field(default=None)
    finished_at: Optional[str] = Field(default=None)
    transcript_segments: List[OmiTranscriptSegment] = Field(
        default_factory=list,
        description="List of raw transcript segments"
    )
    structured: Optional[OmiStructuredData] = Field(
        default=None,
        description="Pre-summarized data from Omi"
    )
    discarded: Optional[bool] = Field(
        default=False,
        description="True if Omi deemed this conversation discarded"
    )
    metadata: Optional[Dict[str, Any]] = Field(
        default_factory=dict,
        description="Optional session metadata"
    )

    model_config = {"extra": "ignore"}

    def get_full_transcript(self) -> str:
        """Helper to concatenate all transcript segments cleanly."""
        if self.transcript_segments:
            texts = [seg.text.strip() for seg in self.transcript_segments if seg.text and seg.text.strip()]
            if texts:
                return " ".join(texts)
        if self.structured:
            if self.structured.overview and self.structured.overview.strip():
                return self.structured.overview.strip()
            if self.structured.summary and self.structured.summary.strip():
                return self.structured.summary.strip()
        return ""
